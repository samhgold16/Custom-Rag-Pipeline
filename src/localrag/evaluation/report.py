"""Write an ``EvalRun`` as a Markdown report (for people) and JSON (for diffing and tooling)."""

from __future__ import annotations

import json
import time
from pathlib import Path

from localrag.evaluation.metrics import ItemResult
from localrag.evaluation.runner import EvalRun

SUMMARY_HEADERS = (
    "Config",
    "Context",
    "Retrieval",
    "Accuracy",
    "Answerable acc.",
    "Unanswerable abstained",
    "False abstentions",
    "Hit@k",
    "MRR",
    "p50 s",
    "p95 s",
)


def _pct(value: float | None) -> str:
    return "–" if value is None else f"{value:.0%}"


def _num(value: float | None, digits: int = 2) -> str:
    return "–" if value is None else f"{value:.{digits}f}"


def _cell(text: str, width: int = 140) -> str:
    flat = " ".join(text.split()).replace("|", "\\|")
    return flat if len(flat) <= width else flat[: width - 1] + "…"


def _mark(result: ItemResult) -> str:
    if result.type == "unanswerable":
        return "✅ abstained" if result.abstained else "❌ answered"
    return "✅" if result.correct else ("❌ abstained" if result.abstained else "❌")


def render_markdown(run: EvalRun, highlight: tuple[str, ...] = ("q07", "q08", "u02")) -> str:
    env = run.environment
    configs = {c.name: c for c in run.configs}
    by_config: dict[str, dict[str, ItemResult]] = {}
    for r in run.results:
        by_config.setdefault(r.config, {})[r.item_id] = r
    item_ids = list(dict.fromkeys(r.item_id for r in run.results))
    first = run.summaries[0] if run.summaries else None

    dirty = " (uncommitted changes)" if env.get("git_dirty") else ""
    chat = f"`{env.get('chat_model')}` (digest `{env.get('chat_model_digest')}`)"
    embed = f"`{env.get('embedding_model')}` (digest `{env.get('embedding_model_digest')}`)"
    lines = [
        f"# Evaluation report: `{Path(run.dataset).stem or 'dataset'}`",
        "",
        "Generated by `rag eval`. Do not edit by hand; re-run to regenerate.",
        "",
        "## Environment",
        "",
        "| | |",
        "| - | - |",
        f"| Timestamp | {env.get('timestamp')} |",
        f"| Git | `{env.get('git_sha')}`{dirty} |",
        f"| Chat model | {chat} |",
        f"| Embedding model | {embed} |",
        f"| Ollama | {env.get('ollama_version')} |",
        f"| Temperature | {env.get('temperature')} |",
        f"| Chunking | {env.get('chunk_size')} chars, {env.get('chunk_overlap')} overlap |",
        f"| Python / platform | {env.get('python')} / {env.get('platform')} |",
        f"| Packages | {', '.join(f'{k} {v}' for k, v in env.get('packages', {}).items())} |",
        f"| Dataset | `{run.dataset}` (sha256 `{env.get('dataset_sha256')}`) |",
        f"| Wall time | {run.seconds:.0f} s |",
        "",
        "## Summary",
        "",
    ]
    if first:
        lines += [
            f"{first.n} questions: {first.answerable} answerable, "
            f"{first.unanswerable} unanswerable. "
            "*Accuracy* scores every question (answerable: required terms present; unanswerable: "
            "abstained). *Hit@k* and *MRR* cover questions with gold sources. Metric definitions: "
            "[`docs/evaluation.md`](../docs/evaluation.md).",
            "",
        ]
    lines += ["| " + " | ".join(SUMMARY_HEADERS) + " |", "|" + " --- |" * len(SUMMARY_HEADERS)]
    for s in run.summaries:
        c = configs[s.config]
        collection = "+hdr-embedded" if c.header_fields else ""
        extras = [
            x
            for x in (
                collection,
                "guardrail" if c.guardrail else "",
                "rewrite" if c.rewrite else "",
            )
            if x
        ]
        lines.append(
            f"| **{s.config}** | {c.context_format} | {c.retrieval.label()}"
            f"{' · ' + ', '.join(extras) if extras else ''} | {_pct(s.accuracy)} | "
            f"{_pct(s.answer_accuracy)} | {_pct(s.abstention_accuracy)} | "
            f"{_pct(s.false_abstention_rate)} | {_pct(s.hit_at_k)} | {_num(s.mrr)} | "
            f"{_num(s.p50_seconds)} | {_num(s.p95_seconds)} |"
        )
    lines += ["", "### Configurations", ""]
    lines += [f"- **{c.name}**: {c.description}" for c in run.configs]

    lines += ["", "## Per-question results", ""]
    lines += ["| Question | " + " | ".join(configs) + " |", "| --- |" + " --- |" * len(configs)]
    for item_id in item_ids:
        row = [by_config[name].get(item_id) for name in configs]
        cells = [("✅" if r.correct else "❌") if r else "" for r in row]
        lines.append(f"| `{item_id}` | " + " | ".join(cells) + " |")

    lines += ["", "## Highlighted questions", ""]
    for item_id in highlight:
        sample = next((r for r in run.results if r.item_id == item_id), None)
        if sample is None:
            continue
        lines += [
            f"### `{item_id}`: {sample.question}",
            "",
            "| Config | Verdict | Sources (rank order) | Answer |",
            "| --- | --- | --- | --- |",
        ]
        for name in configs:
            r = by_config[name].get(item_id)
            if r:
                sources = ", ".join(s.removesuffix(".txt") for s in r.sources) or (
                    f"none (guardrail: {r.guardrail})" if r.guardrail else "none"
                )
                lines.append(f"| {name} | {_mark(r)} | {sources} | {_cell(r.answer)} |")
        lines.append("")

    lines += ["## All answers", ""]
    for name in configs:
        lines += [f"<details><summary><b>{name}</b></summary>", ""]
        lines += ["| Id | Verdict | Sources | Answer |", "| --- | --- | --- | --- |"]
        for item_id in item_ids:
            r = by_config[name].get(item_id)
            if r:
                sources = ", ".join(s.removesuffix(".txt") for s in r.sources) or "none"
                lines.append(f"| `{item_id}` | {_mark(r)} | {sources} | {_cell(r.answer, 300)} |")
        lines += ["", "</details>", ""]
    return "\n".join(lines)


def write_report(run: EvalRun, out_dir: str | Path, name: str | None = None) -> tuple[Path, Path]:
    """Write ``<date>-<dataset>.md`` and ``.json`` into ``out_dir``; return both paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stem = name or f"{time.strftime('%Y-%m-%d')}-{Path(run.dataset).stem or 'eval'}"
    md_path, json_path = out / f"{stem}.md", out / f"{stem}.json"
    md_path.write_text(render_markdown(run) + "\n", encoding="utf-8")
    json_path.write_text(
        json.dumps(run.to_dict(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    return md_path, json_path
